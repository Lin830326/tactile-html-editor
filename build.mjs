// Bundles src/ into two single-file outputs:
//   dist/tactile.html   standalone page (open from disk)
//   dist/artifact.html  body-only page for publishing as a claude.ai Artifact
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const src = join(root, 'src');

// The reading of a workbook is written once, in ingest/src/workbook.mjs. The editor loads classic scripts, so it
// gets the same text with the export taken off and its one function put on window.HE.
{
  const from = readFileSync(join(root, 'ingest', 'src', 'workbook.mjs'), 'utf8').replace(/\r\n/g, '\n');
  if (!from.includes('export function workbookReader(') || /^import\s/m.test(from)) throw new Error('ingest/src/workbook.mjs must export workbookReader and import nothing');
  const text = '/* Tactile — workbook-core.js: GENERATED by build.mjs from ingest/src/workbook.mjs. Do not edit this file. */\n' +
    '(function () {\n  \'use strict\';\n' + from.replace('export function workbookReader(', 'function workbookReader(') +
    '  window.HE.workbookCore = workbookReader;\n})();\n';
  const out = join(src, 'js', 'workbook-core.js');
  if (!existsSync(out) || readFileSync(out, 'utf8').replace(/\r\n/g, '\n') !== text) writeFileSync(out, text);
}
// The arithmetic, the rules and the charts are written once too: modules of ingest that import only one another.
// Each becomes a function of its own inside one classic script, so helpers of the same name stay apart, and what
// they export is put together on window.HE.ingestCore. yaml-lite is there for the editor alone: it reads a
// rules.yaml the user loads, where ingest uses the yaml package.
{
  const names = ['decimal', 'rules-core', 'chart', 'yaml-lite'];
  const made = [];
  const owner = new Map(); // exported name -> the module that exports it
  let body = '';
  for (const name of names) {
    const file = 'ingest/src/' + name + '.mjs';
    let text = readFileSync(join(root, 'ingest', 'src', name + '.mjs'), 'utf8').replace(/\r\n/g, '\n');
    let takes = '';
    text = text.replace(/^import\s*\{([^}]*)\}\s*from\s*'\.\/([\w-]+)\.mjs';[ \t]*\n/gm, (line, list, from) => {
      if (!made.includes(from)) throw new Error(file + ' imports ./' + from + '.mjs; it may import only ' + (made.map((m) => './' + m + '.mjs').join(', ') || 'nothing'));
      if (/\bas\b/.test(list)) throw new Error(file + ' renames an import; build.mjs does not carry that over');
      takes += '    const { ' + list.split(',').map((s) => s.trim()).filter(Boolean).join(', ') + ' } = M[\'' + from + '\'];\n';
      return '';
    });
    if (/^\s*import\b/m.test(text) || /\bimport\s*\(/.test(text) || /\brequire\s*\(/.test(text)) {
      throw new Error(file + ' may import only from ' + names.map((m) => './' + m + '.mjs').join(', ') + ', with import { … } from');
    }
    const gives = [];
    text = text.replace(/^export\s+(?=(?:async\s+)?(?:function\*?|const|let|class)\s+([A-Za-z_$][\w$]*))/gm, (all, id) => { gives.push(id); return ''; });
    if (/^\s*export\b/m.test(text)) throw new Error(file + ' has an export that build.mjs cannot carry over; write export function, const, let or class');
    for (const id of gives) {
      if (owner.has(id)) throw new Error(file + ' and ingest/src/' + owner.get(id) + '.mjs both export ' + id);
      owner.set(id, name);
    }
    body += '  /* ---- ' + file + ' ---- */\n  M[\'' + name + '\'] = (function () {\n' + takes + text + '    return { ' + gives.join(', ') + ' };\n  })();\n';
    made.push(name);
  }
  const text = '/* Tactile — ingest-core.js: GENERATED by build.mjs from ingest/src/' + names.map((m) => m + '.mjs').join(', ') + '. Do not edit this file. */\n' +
    '(function () {\n  \'use strict\';\n  const M = {};\n' + body +
    '  window.HE.ingestCore = Object.assign({}, ' + names.map((m) => 'M[\'' + m + '\']').join(', ') + ');\n})();\n';
  const out = join(src, 'js', 'ingest-core.js');
  if (!existsSync(out) || readFileSync(out, 'utf8').replace(/\r\n/g, '\n') !== text) writeFileSync(out, text);
}
const index = readFileSync(join(src, 'index.html'), 'utf8');

const between = (s, a, b) => {
  const i = s.indexOf(a), j = s.indexOf(b);
  if (i < 0 || j < 0) throw new Error('missing marker ' + a + ' / ' + b);
  return s.slice(i + a.length, j);
};
const refs = (block, re) => [...block.matchAll(re)].map((m) => m[1]);

const cssFiles = refs(between(index, '<!-- @build:css -->', '<!-- @build:css-end -->'), /href="([^"]+)"/g);
const jsFiles = refs(between(index, '<!-- @build:js -->', '<!-- @build:js-end -->'), /src="([^"]+)"/g);

const read = (f) => {
  const p = join(src, f);
  if (!existsSync(p)) { console.warn('  (missing ' + f + ')'); return ''; }
  return readFileSync(p, 'utf8');
};
const css = cssFiles.map((f) => '/* ' + f + ' */\n' + read(f)).join('\n');
// Inline <script> safety: a literal "</script" or "<!--" inside JS strings would end or confuse the element.
const js = jsFiles
  .map((f) => '/* ' + f + ' */\n' + read(f).replace(/<\/script/gi, '<\\/script').replace(/<!--/g, '<\\!--'))
  .join('\n;\n');

const bodyMarkup = between(index, '<!-- @build:body-start -->', '<!-- @build:body-end -->').trim();
const title = (index.match(/<title>[^<]*<\/title>/) || ['<title>Tactile</title>'])[0];

// Each output is distributed on its own, so it carries the whole licence text. "--" would end the comment early.
const licenseText = readFileSync(join(root, 'LICENSE'), 'utf8').replace(/\r\n/g, '\n').trim();
if (licenseText.includes('--')) throw new Error('LICENSE contains "--", which cannot go inside an HTML comment');
// The icons are covered by a notice of their own (THIRD_PARTY_NOTICES.md); the ISC License asks for it in every copy.
const iconsText = readFileSync(join(root, 'licenses', 'LUCIDE.txt'), 'utf8').replace(/\r\n/g, '\n').trim();
if (iconsText.includes('--')) throw new Error('licenses/LUCIDE.txt contains "--", which cannot go inside an HTML comment');
// The address comes from package.json, the one place that holds it (tools/set-repo.mjs changes the others to match).
const repoUrl = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).repository.url.replace(/^git\+/, '').replace(/\.git$/, '');
// The library that reads spreadsheets is in the outputs whole; the Apache License asks for its text in every copy.
const sheetText = readFileSync(join(root, 'licenses', 'SHEETJS.txt'), 'utf8').replace(/\r\n/g, '\n').trim();
if (sheetText.includes('--')) throw new Error('licenses/SHEETJS.txt contains "--", which cannot go inside an HTML comment');
const notice = `<!--
Tactile HTML editor
${repoUrl}

${licenseText}

${'='.repeat(72)}

${iconsText}

${'='.repeat(72)}

${sheetText}
-->`;

const standalone = `<!doctype html>
${notice}
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
${title}
<style>
${css}
</style>
</head>
<body>
${bodyMarkup}
<script>
${js}
</script>
</body>
</html>
`;

const artifact = `${title}
${notice}
<style>
${css}
</style>
${bodyMarkup}
<script>
${js}
</script>
`;

mkdirSync(join(root, 'dist'), { recursive: true });
writeFileSync(join(root, 'dist', 'tactile.html'), standalone);
writeFileSync(join(root, 'dist', 'artifact.html'), artifact);
console.log('built dist/tactile.html (' + (standalone.length / 1024).toFixed(1) + ' KB), dist/artifact.html');
console.log('  css:', cssFiles.join(', '));
console.log('  js :', jsFiles.join(', '));
